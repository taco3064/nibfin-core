describe("renderWorkflows nibfin-issue.yml", () => {
  it("keeps the newline after the rendered lists", () => {
    const content = file(requests["user execution"], "nibfin-issue.yml");
    assert.ok(
      content.includes('\n    workflows: ["Build x", "CI"]\n    types: [completed]\n'),
    );
    assert.ok(
      content.includes('\n  push:\n    branches: ["trunk"]\n\npermissions: {}\n'),
    );
  });

  it("leaves out workflow_run when there are no workflow names", () => {
    const content = file(requests["user peer"], "nibfin-issue.yml");
    assert.ok(!content.includes("workflow_run:\n"));
    assert.ok(content.includes("    types: [submitted]\n  check_suite:\n"));
  });

  it("calls Core's events workflow in the own channel", () => {
    const own = file(requests["own execution"], "nibfin-issue.yml");
    assert.ok(
      own.endsWith(
        "    uses: ./.github/workflows/nibfin-events.yml\n" +
          "    secrets:\n      token: ${{ secrets.NIBFIN_GITHUB_TOKEN }}\n",
      ),
    );
    const peer = file(requests["own peer"], "nibfin-issue.yml");
    assert.ok(
      peer.includes(
        "    uses: taco3064/nibfin-core/.github/workflows/nibfin-events.yml@main\n",
      ),
    );
  });

  it("inlines Core's events job in the user channel", () => {
    for (const request of [requests["user execution"], requests["user peer"]]) {
      const user = file(request, "nibfin-issue.yml");
      assert.ok(!/^ {4}uses:/m.test(user));
      const events = file(requests["own execution"], "nibfin-events.yml");
      const job = (text: string) => text.slice(text.indexOf("\njobs:\n  wake:\n"));
      assert.equal(
        job(user),
        job(events)
          .replace("${{ secrets.token }}", "${{ secrets.NIBFIN_GITHUB_TOKEN }}")
          .replace("nibfin-core/action@main", `nibfin-core/action@${commit}`),
      );
    }
  });

  it("wakes through one step of Core's Action, with no bash rule", () => {
    const action = "taco3064/nibfin-core/action";
    const files = [
      [file(requests["own execution"], "nibfin-events.yml"), `${action}@main`],
      [file(requests["user execution"], "nibfin-issue.yml"), `${action}@${commit}`],
      [file(requests["user peer"], "nibfin-issue.yml"), `${action}@${commit}`],
    ];
    for (const [content, uses] of files) {
      assert.ok(
        content.includes(
          `        uses: ${uses}\n        with:\n          command: wake\n` +
            "          token: ${{ secrets.",
        ),
      );
      assert.ok(
        content.endsWith("          execution-repo: ${{ vars.NIBFIN_EXECUTION_REPO }}\n"),
      );
      assert.equal(count(content, "uses: "), 1);
      for (const part of [
        "run: |",
        "gh_retry",
        "rate_limit_delay",
        "flag_targets",
        "resolve_shas",
        "WAKE_FAILED",
        "curl",
        "env:",
      ]) {
        assert.ok(!content.includes(part), part);
      }
    }
  });

  it("is the same with and without an image for a peer set", () => {
    for (const [name, image] of [
      ["own peer", "ghcr.io/taco3064/nibfin:main"],
      ["user peer", zero],
    ] as const) {
      const request = requests[name];
      assert.deepEqual(renderWorkflows({ ...request, image }), renderWorkflows(request));
    }
  });
});

describe("renderWorkflows nibfin-job.yml", () => {
  const user = () => file(requests["user execution"], "nibfin-job.yml");
  const own = () => file(requests["own execution"], "nibfin-job.yml");

  it("pins the user image on one top-level line", () => {
    const lines = user().split("\n");
    assert.equal(lines.filter((line) => hookLine.test(line)).length, 1);
    assert.ok(
      user().includes(
        `\nenv:\n  IMAGE: ghcr.io/taco3064/nibfin\n  IMAGE_REF: ${real}\n\ndefaults:\n`,
      ),
    );
  });

  it("differs only on the hook line between a zero and a real digest", () => {
    const zeroLines = file(
      { ...requests["user execution"], image: zero },
      "nibfin-job.yml",
    ).split("\n");
    const realLines = user().split("\n");
    assert.equal(zeroLines.length, realLines.length);
    const changed = realLines.flatMap((line, index) =>
      line === zeroLines[index] ? [] : [index],
    );
    assert.equal(changed.length, 1);
    assert.match(realLines[changed[0]], hookLine);
    assert.match(zeroLines[changed[0]], hookLine);
  });

  it("gives every user run step the image a pull step wrote", () => {
    const content = user();
    for (const line of content
      .split("\n")
      .filter((text) => text.includes("IMAGE_REF:"))) {
      assert.ok(
        hookLine.test(line) ||
          line === "          IMAGE_REF: ${{ steps.image.outputs.ref }}",
        line,
      );
    }
    const jobs = content.split(/\n {2}(?=(?:route|finish|stage):\n)/).slice(1);
    assert.equal(jobs.length, 3);
    for (const job of jobs) {
      const steps = job.split("\n      - name: ");
      const pull = steps.findIndex(
        (step) =>
          step.includes("\n        id: image\n") &&
          step.includes('echo "ref=$IMAGE_REF" >> "$GITHUB_OUTPUT"'),
      );
      const users = steps.flatMap((step, index) =>
        step.includes("IMAGE_REF: ${{ steps.image.outputs.ref }}") ? [index] : [],
      );
      assert.ok(pull > 0);
      assert.equal(users.length, 1);
      assert.ok(users[0] > pull);
    }
  });

  it("logs the image in every pull step", () => {
    assert.equal(count(user(), '\n          echo "Nibfin image: $IMAGE_REF"\n'), 3);
    assert.equal(count(user(), 'podman pull "$IMAGE_REF"\n'), 3);
    assert.equal(count(own(), '\n          echo "Nibfin image: $IMAGE@$digest"\n'), 3);
    assert.equal(count(own(), 'podman pull "$IMAGE:main"\n'), 3);
    assert.ok(!own().includes("\n  IMAGE_REF: "));
  });

  it("renders the one pending step, Core's Action, in all three Jobs", () => {
    const step = (uses: string) =>
      "      - name: Ask a person to act\n" +
      "        if: failure() && inputs.issue != ''\n" +
      `        uses: ${uses}\n` +
      "        with:\n" +
      "          command: job-failed\n" +
      "          token: ${{ secrets.token }}\n" +
      "          repo: ${{ inputs.repo }}\n" +
      "          issue: ${{ inputs.issue }}\n" +
      "          stage: ${{ inputs.stage }}\n";
    const action = "taco3064/nibfin-core/action";
    for (const [content, uses] of [
      [user(), `${action}@${commit}`],
      [own(), `${action}@main`],
    ]) {
      assert.equal(count(content, step(uses)), 3);
      assert.equal(count(content, "      - name: Ask a person to act\n"), 3);
      assert.equal(count(content, "uses: taco3064/nibfin-core/action@"), 3);
      for (const part of ["curl", "call()", "GITHUB_SERVER_URL"]) {
        assert.ok(!content.includes(part), part);
      }
    }
  });

  it("labels the containers with the namespaced names only", () => {
    for (const content of [user(), own()]) {
      assert.equal(count(content, '--label "io.github.taco3064.nibfin.repo=$REPO"'), 3);
      assert.equal(count(content, '--label "io.github.taco3064.nibfin.issue=$ISSUE"'), 3);
      assert.ok(!/"nibfin\.(repo|issue)=/.test(content));
    }
  });
});

