describe("workflow templates", () => {
  it("hold no Eta delimiter outside an Eta tag", async () => {
    const sources = await templateSources(defaultTemplateDir);
    assert.ok(sources.length > 0);
    for (const source of sources) {
      const literal = source.replace(/<%[\s\S]*?%>/g, "");
      assert.ok(!literal.includes("<%") && !literal.includes("%>"));
    }
  });
});

describe("renderWorkflows template errors", () => {
  let views: string;
  before(async () => {
    views = await makeTempDir("workflow-templates-");
  });
  after(() => rm(views, { recursive: true, force: true }));
  const peer = requests["user peer"];

  async function template(text: string) {
    await mkdir(views, { recursive: true });
    await writeFile(join(views, "nibfin-issue.yml.eta"), text);
  }

  it("fails on a value the request leaves unset", async () => {
    await template("image: <%~ it.imageRef %>\n");
    assert.throws(() => renderWorkflows(peer, views), TemplateValueError);
  });

  it("fails on a misspelt value", async () => {
    await template("branches: <%= it.branch %>\n");
    assert.throws(() => renderWorkflows(peer, views), TemplateValueError);
  });

  it("fails on a missing fragment", async () => {
    await template('<%~ include("/fragments/missing.eta", it) -%>\n');
    assert.throws(() => renderWorkflows(peer, views), EtaFileResolutionError);
  });

  it("fails on a missing template", async () => {
    await template("name: ok\n");
    assert.throws(
      () => renderWorkflows(requests["user execution"], views),
      EtaFileResolutionError,
    );
  });
});
