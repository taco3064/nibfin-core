const repoRoot = fileURLToPath(new URL("../../", import.meta.url));
const zero = `ghcr.io/taco3064/nibfin@sha256:${"0".repeat(64)}`;
const real = `ghcr.io/taco3064/nibfin@sha256:${"ab".repeat(32)}`;
const commit = "0123456789abcdef0123456789abcdef01234567";
const hookLine = /^ {2}IMAGE_REF: ghcr\.io\/taco3064\/nibfin@sha256:([0-9a-f]{64})$/;

const requests: Record<string, RenderRequest> = {
  "own execution": {
    set: "execution",
    channel: "own",
    image: "ghcr.io/taco3064/nibfin:main",
    defaultBranch: "main",
    workflows: ["CI", "Image"],
  },
  "own peer": { set: "peer", channel: "own", defaultBranch: "main", workflows: ["CI"] },
  "user execution": {
    set: "execution",
    channel: "user",
    image: real,
    defaultBranch: "trunk",
    workflows: ["Build x", "CI"],
    commit,
  },
  "user peer": {
    set: "peer",
    channel: "user",
    defaultBranch: "trunk",
    workflows: [],
    commit,
  },
};

function file(request: RenderRequest, name: string): string {
  const content = renderWorkflows(request)[`.github/workflows/${name}`];
  assert.ok(content !== undefined, `${name} is rendered`);
  return content;
}

function count(text: string, part: string): number {
  return text.split(part).length - 1;
}

async function templateSources(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  const files = entries.filter((entry) => entry.isFile());
  return Promise.all(
    files.map((entry) => readFile(join(entry.parentPath, entry.name), "utf8")),
  );
}

describe("renderWorkflows sets", () => {
  const expected: Record<string, string[]> = {
    "own execution": [
      "nibfin-e2e-notify.yml",
      "nibfin-events.yml",
      "nibfin-issue.yml",
      "nibfin-job.yml",
      "nibfin-runner-request.yml",
      "nibfin-shared-runner.yml",
    ],
    "own peer": ["nibfin-e2e-notify.yml", "nibfin-issue.yml"],
    "user execution": [
      "nibfin-issue.yml",
      "nibfin-job.yml",
      "nibfin-runner-request.yml",
      "nibfin-shared-runner.yml",
    ],
    "user peer": ["nibfin-issue.yml"],
  };
  for (const [name, request] of Object.entries(requests)) {
    it(`renders the ${name} files in sorted order`, () => {
      const paths = expected[name].map((file) => `.github/workflows/${file}`);
      assert.deepEqual(Object.keys(renderWorkflows(request)), paths);
    });

    it(`renders the ${name} files deterministically`, () => {
      assert.deepEqual(renderWorkflows(request), renderWorkflows(request));
    });

    it(`leaves no template tag or undefined value in the ${name} files`, () => {
      for (const content of Object.values(renderWorkflows(request))) {
        assert.ok(!content.includes("<%") && !content.includes("%>"));
        assert.ok(!/\bundefined\b/.test(content));
        assert.ok(content.endsWith("\n") && !content.endsWith("\n\n"));
      }
    });

    it(`renders ${name} files that Prettier leaves unchanged`, async () => {
      for (const [path, content] of Object.entries(renderWorkflows(request))) {
        const options = await prettier.resolveConfig(join(repoRoot, path));
        assert.equal(options?.printWidth, 90);
        const checked = await prettier.check(content, { ...options, parser: "yaml" });
        assert.ok(checked, `${name} ${path} is formatted`);
      }
    });
  }
});

